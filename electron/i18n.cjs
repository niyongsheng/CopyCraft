const LANGUAGE_IDS = ['zh-CN', 'zh-TW', 'en', 'ja', 'ko'];
let currentLanguage = 'zh-CN';

function normalizeLanguage(language) {
  return LANGUAGE_IDS.includes(language) ? language : 'zh-CN';
}

function setLanguage(language) {
  currentLanguage = normalizeLanguage(language);
}

function getLanguage() {
  return currentLanguage;
}

function t(key, vars) {
  const table = MESSAGES[currentLanguage] ?? MESSAGES['zh-CN'];
  const template = table[key] ?? MESSAGES['zh-CN'][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

module.exports = { LANGUAGE_IDS, setLanguage, getLanguage, t };
